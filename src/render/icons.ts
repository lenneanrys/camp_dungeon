const cache = new Map<string, Path2D>()

/** Path2D objects are expensive to build, so keep one per icon. */
export function iconPath(id: ButtonId): Path2D {
  let p = cache.get(id)
  if (!p) {
    p = new Path2D(ICONS[id].path)
    cache.set(id, p)
  }
  return p
}
